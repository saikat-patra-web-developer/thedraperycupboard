/**
 * Helper to find a single part by slug or ID
 */
export function findPart(slugOrId) {
  return parts.find((p) => p.slug === slugOrId || p.id === slugOrId);
}

/**
 * Filter parts by category
 */
export function getPartsByCategory(categoryId) {
  if (!categoryId || categoryId === "all") return parts;
  return parts.filter((p) => p.category === categoryId);
}
