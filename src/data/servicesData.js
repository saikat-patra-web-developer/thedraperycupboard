export function findService(slugOrAlias) {
  if (!slugOrAlias) return null;
  const normalized = slugOrAlias
    .toLowerCase()
    .replace(/^https?:\/\/[^/]+/i, "")
    .replace(/^\/|\/$/g, "")
    .replace(/^services\//, "");

  return servicesData.find(
    (s) =>
      s.slug === normalized ||
      s.id === normalized ||
      s.aliases.includes(normalized)
  );
}

